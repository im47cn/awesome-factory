# ── 标准缩写白名单（仅作符号集中，ddl_check 未引用，预留扩展） ──────
# 用法示例：当需做"非标准缩写"反向检查时，遍历该集合发现 key ∉ LONG_TO_SHORT
# 即报错。ddl-guard 当前仅做"长写法 → 缩写"单向检查，未启用该集合。

STANDARD_SHORT: set[str] = set(LONG_TO_SHORT.values())


# ── value 保留字的 key 豁免集 ─────────────────────────────────────────
# 部分字典条目的 value 是 MySQL 保留字或 Python 关键字（如 character→char、
# delete→del、number→no）。如果强制把字段名 `character` 改为 `char`，
# `char` 本身又会触发 check_field_name 的 "保留字" 违规，造成无法满足两条
# 相互冲突的强制规则的违规循环。此类条目跳过反向检查，视为"已合规"。
# 注意：集合中存放的是 `LONG_TO_SHORT` 的 **key**（如 `character`），不是 value。
KEYS_WITH_RESERVED_VALUE: set[str] = {
    # MySQL 保留字
    "across", "character", "december", "default", "delete", "enumerate",
    "inside", "loading", "number", "sets",
    # Python 关键字
    "asynchronous", "classification",
}


def strip_index_prefix(name: str) -> str:
    """去掉索引名前缀 `ix_` / `uk_`，返回剩余分词字符串。"""
    low = name.lower()
    return low[3:] if low.startswith(("uk_", "ix_")) else low


def iter_abbrev_violations(name: str) -> list[tuple[str, str]]:
    """对名称（含 `snake_case` 分词）做最长匹配检查，返回 [(命中分词, 标准缩写), ...]。

    按 `_` 拆分后从左到右扫描，每个位置优先尝试最长的多词短语命中字典 key
    （如 `cargo_owner_id` 命中 `cargo_owner → cgoer`），命中后消费短语覆盖的
    全部分词；无短语命中时退回单词匹配（如 `mapping_id` 命中 `mapping → mapp`）。

    自我映射（key == value，如 `carrier → carrier`）与同字复合短语（如
    `value_date → value_date`）不报违规，但同样消费其分词，避免
    `value → val` 之类的拆词误报。
    返回结果去重：同一 (分词, value) 组合只返回一次。
    """
    raw_violations: list[tuple[str, str]] = []
    parts = name.lower().split("_")

    i = 0
    while i < len(parts):
        step = 1
        # 最长优先：从整个剩余串向左收缩，尝试多词短语命中字典 key
        for j in range(len(parts), i, -1):
            phrase = "_".join(parts[i:j])
            if phrase in LONG_TO_SHORT:
                std = LONG_TO_SHORT[phrase]
                # 链式缩写折叠：value 本身又是字典 key（如 website→web、
                # web→onln）时改报终点标准形，避免按建议整改后二次违规
                chain = {phrase}
                while std in LONG_TO_SHORT and std not in chain:
                    nxt = LONG_TO_SHORT[std]
                    if nxt == std:
                        break
                    chain.add(std)
                    std = nxt
                if std != phrase and phrase not in KEYS_WITH_RESERVED_VALUE:
                    raw_violations.append((phrase, std))
                step = j - i  # 消费短语覆盖的全部分词（含同字映射，不拆词复报）
                break
        i += step

    # 去重：保留首次出现顺序
    seen = set()
    unique: list[tuple[str, str]] = []
    for v in raw_violations:
        if v not in seen:
            seen.add(v)
            unique.append(v)
    return unique
